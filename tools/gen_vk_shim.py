"""Android: the Vulkan commands libmain.so calls, as functions of its own, forwarding to the driver the runtime chose.
    python3 tools/gen_vk_shim.py <out.c> <names.txt> <vulkan_core.h> [more headers ...]
names.txt: the vk* symbols libmain.so's other objects leave undefined (the Makefile lists them with llvm-nm -u), so only
what is called gets a function (the headers also hold beta and vendor commands the NDK's own build never compiles).

libmain.so does not link libvulkan.so: the runtime, ImGui's Vulkan backend and FSR 2 call vkFoo as always, and these
definitions (hidden: nothing outside libmain.so sees or binds to them) send each call to the loader
runtime/platform/android_vk.c opened - the system's, or a second copy whose driver is a custom one (Mesa's Turnip,
through libadrenotools: LARECOMP_VK_DRIVER). Each command is looked up once, at its first call: vkGetInstanceProcAddr
with no instance before vkCreateInstance, with the instance after (a device command's pointer is then the loader's
trampoline, valid for any device). The prototypes come from the NDK's own headers, so the list follows its Vulkan
version."""
import re
import sys

PROTO = re.compile(r'VKAPI_ATTR\s+([\w ]+?\**)\s*VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;')


def arg_names(params):
    params = ' '.join(params.split())
    if params in ('', 'void'):
        return []
    names = []
    for p in params.split(','):
        p = re.sub(r'\[.*?\]', '', p).strip()  # (const float blendConstants[4])
        names.append(re.findall(r'\w+', p)[-1])
    return names


def main(out, names_file, headers):
    want = set(open(names_file).read().split())
    seen, lines = set(), []
    for h in headers:
        text = open(h).read()
        for ret, name, params in PROTO.findall(text):
            if name in seen or name not in want:
                continue
            seen.add(name)
            params = ' '.join(params.split())
            call = ', '.join(arg_names(params))
            ret = ret.strip()
            if name == 'vkGetInstanceProcAddr':  # (the real one: what it hands out bypasses this table)
                body = f'return vk_shim_gipa()({call});'
            elif name == 'vkCreateInstance':
                body = (f'if (!p_{name}) p_{name} = (PFN_{name})vk_shim_resolve("{name}");\n'
                        f'    VkResult r = p_{name}({call});\n'
                        f'    if (r == VK_SUCCESS) vk_shim_instance(*pInstance);\n    return r;')
            else:
                ret_kw = '' if ret == 'void' else 'return '
                body = (f'if (!p_{name}) p_{name} = (PFN_{name})vk_shim_resolve("{name}");\n'
                        f'    {ret_kw}p_{name}({call});')
            lines.append(f'static PFN_{name} p_{name};\n'
                         f'VKS VKAPI_ATTR {ret} VKAPI_CALL {name}({params}) {{\n    {body}\n}}\n')
    with open(out, 'w') as f:
        f.write('// Generated by tools/gen_vk_shim.py from the NDK\'s Vulkan headers: do not edit.\n'
                '#define VK_NO_PROTOTYPES\n#include <vulkan/vulkan.h>\n#include <vulkan/vulkan_android.h>\n\n'
                '#define VKS __attribute__((visibility("hidden")))\n'
                'PFN_vkGetInstanceProcAddr vk_shim_gipa(void);\n'
                'PFN_vkVoidFunction vk_shim_resolve(const char *name);\n'
                'void vk_shim_instance(VkInstance inst);\n\n')
        f.write('\n'.join(lines))
    missing = sorted(want - seen)
    if missing:  # (the link would then fail on them: say which header lacks them)
        sys.exit(f'gen_vk_shim: no prototype for {" ".join(missing)}')
    print(f'{out}: {len(seen)} commands')


if __name__ == '__main__':
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
